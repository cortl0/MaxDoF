#pragma once

namespace MaxDoF::GameCommon::LevelGraph
{
    // =========================================================================
    // БАЗОВЫЕ ФИЗИЧЕСКИЕ И ГЕОМЕТРИЧЕСКИЕ КОНСТАНТЫ УРОВНЯ
    // =========================================================================

    // Радиус сферы корабля игрока в метрах (Диаметр = 1.0 метр)
    constexpr float cShipSphereRadius = 0.5f;

    /**
     * @brief МИНИМАЛЬНАЯ ДЛИНА РЕБРА ДЛЯ ПРАВИЛЬНОГО ТРЕУГОЛЬНИКА (СЕЧЕНИЯ ТРУБЫ)
     *
     * МАТЕМАТИЧЕСКОЕ ОБОСНОВАНИЕ:
     * Окружность (сечение корабля) должна быть вписана в равносторонний треугольник.
     * Формула радиуса вписанной окружности: r = a / (2 * sqrt(3))
     * Отсюда длина ребра: a = 2 * sqrt(3) * r
     *
     * Для r = 0.5м: a = 2 * 1.7320508 * 0.5 = sqrt(3) ≈ 1.7320508 метров.
     * При такой длине ребра корабль зажат стенами туннеля впритирку по осям X и Y.
     */
    constexpr float cMinTriangleEdgeLength = 2.0f * 1.7320508f * cShipSphereRadius;

    /**
     * @brief МИНИМАЛЬНАЯ ДЛИНА РЕБРА ДЛЯ ПРАВИЛЬНОГО ТЕТРАЭДРА (УЗЛА ГРАФА)
     *
     * МАТЕМАТИЧЕСКОЕ ОБОСНОВАНИЕ:
     * Сфера корабля должна быть вписана внутрь объемной пирамиды-тетраэдра.
     * Формула радиуса вписанной сферы: r = a / sqrt(24) = a / (2 * sqrt(6))
     * Отсюда длина ребра: a = 2 * sqrt(6) * r
     *
     * Для r = 0.5м: a = 2 * 2.4494897 * 0.5 = sqrt(6) ≈ 2.4494897 метров.
     * При такой длине ребра корабль касается всех 4-х плоских стен тетраэдра одновременно.
     */
    constexpr float cMinTetrahedronEdgeLength = 2.0f * 2.4494897f * cShipSphereRadius;

    // =========================================================================
    // КОЭФФИЦИЕНТЫ КОМФОРТА (Плейтест / Игровой баланс)
    // =========================================================================

    // Множитель для создания свободного пространства вокруг корабля.
    // Изменяя этот коэффициент, мы пропорционально расширяем весь лабиринт астероида.
    constexpr float cGameplayComfortFactor = 1.0f; // 1.0f - жестко впритирку (2.45м / 1.73м)

    // Итоговые рабочие константы генератора с учетом геймплейного запаса
    constexpr float cEffectiveMinTriangleEdge    = cMinTriangleEdgeLength * cGameplayComfortFactor;
    constexpr float cEffectiveMinTetrahedronEdge = cMinTetrahedronEdgeLength * cGameplayComfortFactor;
}
